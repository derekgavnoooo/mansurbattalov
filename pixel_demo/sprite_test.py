def render(art, scale=10, bg="#fcc6dd"):
    rows = [r for r in art.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    im = Image.new("RGB", (w, len(rows)), bg)
    px = im.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r.ljust(w, ".")):
            c = PAL.get(ch)
            if c:
                px[x, y] = tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))
    return im.resize((w * scale, len(rows) * scale), Image.NEAREST)


