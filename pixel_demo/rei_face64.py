"""Лицо Рэй 64×64, 1 бит — по пикселям, без многоугольников и без автоматического дизеринга.

Символы сетки:
  #  чёрный          .  белый
  :  шахматка 50%    -  редкие точки 25% (тень на коже/волосах)
  =  тёмный фон 75%
Узоры полутонов выбраны вручную под материал; каждая точка черт лица поставлена явно.
"""
import sys
from PIL import Image

Wd = Hd = 64
G = [["="] * Wd for _ in range(Hd)]


def put(x, y, c):
    if 0 <= x < Wd and 0 <= y < Hd:
        G[y][x] = c


def span(y, x0, x1, c):
    for x in range(x0, x1 + 1):
        put(x, y, c)


def pts(c, *xy):
    for x, y in xy:
        put(x, y, c)


# ---- ахоге и макушка ----
pts("#", (34, 0), (35, 0), (33, 1), (35, 1), (32, 2))
put(34, 1, ".")
span(2, 26, 37, "#")
span(3, 21, 25, "#"); span(3, 26, 37, "."); span(3, 38, 42, "#")
span(4, 18, 20, "#"); span(4, 21, 40, "."); span(4, 41, 42, "-"); span(4, 43, 45, "#")
span(5, 16, 17, "#"); span(5, 18, 39, "."); span(5, 40, 43, "-"); span(5, 44, 45, ":"); span(5, 46, 47, "#")
span(6, 14, 15, "#"); span(6, 16, 38, "."); span(6, 39, 42, "-"); span(6, 43, 46, ":"); span(6, 47, 49, "#")
OUT = {7: (13, 50), 8: (12, 51), 9: (11, 52), 10: (10, 53)}
for y in range(11, 23):
    OUT[y] = (9, 54)
for y in range(23, 45):
    OUT[y] = (8, 55)
for y, (a, b) in OUT.items():
    put(a, y, "#")
    span(y, a + 1, 36, ".")
    span(y, 37, 41, "-")
    span(y, 42, b - 1, ":")
    put(b, y, "#")
    if a > 9 and y < 11:
        put(a + 1, y, "#") if y == 7 else None

# блик на волосах — светлая дуга через теневую сторону
span(10, 36, 46, "."); span(11, 44, 50, "."); span(9, 33, 40, ".")

# ---- пряди: точечные линии от макушки к ложбинкам чёлки ----
strands = [
    [(27, 5), (27, 6), (26, 8), (26, 9), (25, 11), (24, 13), (24, 15), (23, 17), (23, 19), (22, 21)],
    [(32, 6), (32, 8), (33, 10), (33, 12), (33, 14), (34, 16), (34, 18), (34, 20)],
    [(37, 7), (38, 9), (38, 11), (39, 13), (39, 15), (40, 17), (40, 19), (40, 21)],
    [(22, 8), (21, 10), (20, 12), (19, 14), (18, 16), (17, 18), (16, 20)],
    [(42, 9), (43, 11), (44, 13), (44, 15), (45, 17), (45, 19), (46, 21)],
]
for s in strands:
    pts("#", *s)

# ---- кромка чёлки: последняя строка волос для каждого столбца (кончики и ложбинки выбраны вручную) ----
EDGE = {14: 30, 15: 26, 16: 23, 17: 26, 18: 30, 19: 33, 20: 30, 21: 27, 22: 24, 23: 26, 24: 29, 25: 31, 26: 28,
        27: 26, 28: 23, 29: 27, 30: 32, 31: 36, 32: 32, 33: 27, 34: 23, 35: 26, 36: 28, 37: 31, 38: 29, 39: 26,
        40: 24, 41: 27, 42: 30, 43: 33, 44: 30, 45: 26, 46: 23, 47: 25, 48: 28, 49: 30}
FACE_L = {y: 15 for y in range(22, 45)}
FACE_L.update({45: 16, 46: 16, 47: 17, 48: 17, 49: 18, 50: 19, 51: 20, 52: 21, 53: 23, 54: 25, 55: 27, 56: 30})
FACE_R = {y: 48 for y in range(22, 45)}
FACE_R.update({45: 47, 46: 47, 47: 46, 48: 46, 49: 45, 50: 44, 51: 43, 52: 42, 53: 40, 54: 38, 55: 36, 56: 34})
for y in range(22, 57):
    a, b = FACE_L[y], FACE_R[y]
    for x in range(a + 1, b):
        e = EDGE.get(x, 99)
        if y > e:
            # кожа: тень сразу под чёлкой, затем белое; правая щека — в тени
            if y == e + 1:
                c = ":"
            elif y == e + 2:
                c = "-"
            elif x >= 43 and 37 <= y <= 51:
                c = "-"
            else:
                c = "."
            put(x, y, c)
        elif y == e:
            put(x, y, "#")
    if y >= 31:
        put(a, y, "#")
        put(b, y, "#")
for x, e in EDGE.items():                 # заполнить «ступеньки» кромки, чтобы линия была непрерывной
    nxt = EDGE.get(x + 1)
    if nxt is not None:
        for y in range(min(e, nxt), max(e, nxt) + 1):
            if G[y][x] not in "#" and y <= max(e, nxt) and (y <= e or y <= nxt):
                if abs(y - e) <= abs(y - nxt) and y <= e:
                    put(x, y, "#") if y > min(e, nxt) - 1 and y >= e - 0 else None
span(56, 30, 34, "#")

# ---- боковые пряди каре с кончиками ----
for y in range(45, 54):
    for x in range(8, 16):
        if FACE_L.get(y, 8) >= x or y < 45:
            put(x, y, "." if x < 13 else "-")
    for x in range(48, 56):
        if FACE_R.get(y, 56) <= x:
            put(x, y, ":")
pts("#", (8, 45), (8, 46), (8, 47), (8, 48), (9, 49), (9, 50), (10, 51), (10, 52), (11, 51), (12, 50), (13, 51),
    (13, 52), (14, 53), (15, 52))
pts("#", (55, 45), (55, 46), (55, 47), (55, 48), (54, 49), (54, 50), (53, 51), (53, 52), (52, 51), (51, 50),
    (50, 51), (50, 52), (49, 53), (48, 52))
for y in range(53, 64):
    span(y, 8, 15, "=") if y > 53 else None
    span(y, 48, 55, "=") if y > 53 else None
pts("#", (11, 30), (11, 34), (12, 38), (12, 42), (52, 31), (52, 35), (51, 39), (51, 43))   # пряди на боках

# ---- глаза (правый — зеркало левого) ----
LEFT_EYE = {
    33: "#.........",
    34: ".#.#####..",
    35: "..#######.",
    36: ".#.####...",
    37: "...#.##...",
    38: "...####...",
    39: "....##....",
    40: "..#....#..",
    41: "...#.#.#..",
}
for y, row in LEFT_EYE.items():
    for i, ch in enumerate(row):
        if ch == "#":
            put(18 + i, y, "#")
            put(63 - (18 + i), y, "#")
        elif ch == "." and G[y][18 + i] not in ":-":
            pass
pts(".", (22, 37), (63 - 23, 37))         # блик (у правого глаза смещён к носу — свет общий)
put(41, 37, "#")

# брови «домиком»
pts("#", (20, 32), (21, 31), (22, 31), (23, 30), (24, 30))
pts("#", (43, 32), (42, 31), (41, 31), (40, 30), (39, 30))

# нос, рот, румянец
pts("#", (33, 45), (32, 46))
span(50, 29, 34, "#")
pts("#", (28, 51), (35, 51))
pts("#", (19, 44), (20, 43), (22, 44), (23, 43), (44, 44), (43, 43), (41, 44), (40, 43))

# заколка-крестик
pts("#", (17, 13), (21, 13), (18, 14), (20, 14), (19, 15), (18, 16), (20, 16), (17, 17), (21, 17))

# ---- шея, плечи, воротник ----
for y in range(57, 64):
    put(26, y, "#")
    put(37, y, "#")
    span(y, 27, 36, ":" if y < 59 else "-")
for y in range(59, 64):
    span(y, 6 - (y - 59), 25, "#")
    span(y, 38, 57 + (y - 59), "#")
span(59, 8, 25, ".")                      # контровой свет по левому плечу
pts(".", (5, 60), (6, 60), (7, 60), (4, 61), (5, 61), (3, 62), (2, 63))
for y, (a, b) in {59: (26, 28), 60: (27, 29), 61: (28, 30), 62: (29, 31)}.items():
    span(y, a, b, ".")
    span(y, 63 - b, 63 - a, ".")
pts("#", (26, 59), (37, 59))
span(63, 31, 32, ":")


def to_text():
    return "\n".join("".join(r) for r in G)


def render(scale=10):
    im = Image.new("1", (Wd, Hd), 1)
    px = im.load()
    for y in range(Hd):
        for x in range(Wd):
            c = G[y][x]
            black = (c == "#" or (c == ":" and (x + y) % 2 == 0) or (c == "-" and x % 2 == 0 and y % 2 == 0)
                     or (c == "=" and not (x % 2 == 0 and y % 2 == 0)))
            px[x, y] = 0 if black else 1
    return im.convert("L").resize((Wd * scale, Hd * scale), Image.NEAREST)


if __name__ == "__main__":
    open(sys.argv[1] + ".txt", "w").write(to_text())
    render().save(sys.argv[1] + ".png")
