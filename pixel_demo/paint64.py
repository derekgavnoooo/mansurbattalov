"""Ручные правки сетки: карандаш (точка), линия (Брезенхем, как в MS Paint), заливка строки."""
import sys
from grid1bit import load

rows = [list(r) for r in load("rei_face64.txt")]


def P(x, y, c="#"):
    if 0 <= x < 64 and 0 <= y < 64:
        rows[y][x] = c


def line(x0, y0, x1, y1, c="#"):
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
    err = dx + dy
    while True:
        P(x0, y0, c)
        if (x0, y0) == (x1, y1):
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy; x0 += sx
        if e2 <= dx:
            err += dx; y0 += sy


def row(y, x0, s):
    for i, ch in enumerate(s):
        P(x0 + i, y, ch)


# 1) очистить область чёлки и глаз на лице
for y in range(20, 42):
    for x in range(11, 49):
        rows[y][x] = "."
# 2) кромка чёлки — зигзаг линией по выбранным точкам (кончики и ложбинки)
Z = [(11, 24), (13, 28), (16, 21), (19, 31), (22, 21), (25, 29), (28, 21), (30, 34), (33, 21), (35, 29), (38, 21),
     (41, 31), (44, 21), (46, 28), (48, 24)]
for (a, b), (c, d) in zip(Z, Z[1:]):
    line(a, b, c, d)
# тень на коже под кончиками прядей (шахматка, 1–2 пикселя)
for (x, y) in [(13, 29), (12, 29), (14, 29), (19, 32), (18, 32), (20, 32), (25, 30), (24, 30), (26, 30),
               (30, 35), (29, 35), (31, 35), (35, 30), (34, 30), (36, 30), (41, 32), (40, 32), (42, 32), (46, 29), (45, 29), (47, 29)]:
    P(x, y, ":")
# пряди внутри чёлки
for (a, b, c, d) in [(16, 12, 16, 20), (22, 12, 22, 20), (28, 13, 28, 20), (33, 12, 33, 20), (38, 13, 38, 20), (44, 12, 44, 20),
                     (19, 23, 19, 28), (25, 23, 25, 26), (30, 23, 30, 30), (35, 23, 35, 26), (41, 23, 41, 28)]:
    line(a, b, c, d)
# тень справа на чёлке
for y in range(20, 30):
    for x in range(45, 49):
        if rows[y][x] == "." and y < 26:
            rows[y][x] = "-"
# 3) брови «домиком»: внутренние концы выше
for (x, y) in [(15, 32), (16, 32), (17, 31), (18, 31), (21, 30), (22, 30)]:
    P(x, y)
for (x, y) in [(47, 32), (46, 32), (45, 31), (44, 31), (41, 30), (40, 30)]:
    P(x, y)
# 4) глаза — штамп, правый зеркален (c → 62 - c), веки опускаются к внешним углам
EYE = {33: ".......###", 34: "....######", 35: "..########", 36: "##..####..", 37: "...#.###..",
       38: "...####...", 39: "....##....", 40: "..#.....#."}
for y, s in EYE.items():
    for i, ch in enumerate(s):
        if ch == "#":
            P(15 + i, y)
            P(62 - (15 + i), y)
P(19, 37, "."); P(43, 37, ".")              # блики
P(42, 37, "#")
# 5) нос, румянец
for (x, y) in [(31, 44), (30, 45)]:
    P(x, y)
for (x, y) in [(15, 43), (16, 42), (18, 43), (19, 42), (47, 43), (46, 42), (44, 43), (43, 42)]:
    P(x, y)
# 6) низ: рот, подбородок, шея, воротник — переписать строки 48–63 целиком
for y in range(48, 64):
    rows[y] = list("=" * 64)
for y in range(48, 53):                       # боковые пряди каре с кончиками
    row(y, 8, "#.#")
    row(y, 50, "#::::::#")
row(48, 11, "." * 38); P(10, 48); P(49, 48)
row(49, 11, "." * 38); P(10, 49); P(49, 49)
row(50, 11, "." * 38); P(11, 50); P(48, 50)
row(51, 12, "." * 36); P(12, 51); P(47, 51)
row(52, 13, "." * 34); P(13, 52); P(46, 52)
row(53, 8, "#.#.#"); row(53, 14, "#" + "." * 30 + "#"); row(53, 50, "#:#::#:#")
row(54, 8, "=##=#"); row(54, 16, "##" + "." * 26 + "##"); row(54, 50, "=#=##=#")
row(55, 18, "####" + "." * 18 + "####")
row(56, 22, "#####" + "....." + "#####")       # подбородок
row(57, 24, "#::::::::::::#")
row(58, 24, "#::----------::#"[:14])
row(59, 4, "." * 19 + "#" + "-" * 12 + "#" + "." * 6 + "#" * 18)
row(60, 3, "..####################" + ".." + "-" * 8 + ".." + "#" * 22)
row(61, 2, ".######################" + "..." + "----" + "..." + "#" * 23)
row(62, 1, ".#######################" + "...." + "::" + "...." + "#" * 24)
row(63, 0, ".########################" + "...." + "::" + "...." + "#" * 25)
# рот: маленький, уголки вниз
for y in (48, 49, 50, 51):
    pass
for x in range(28, 34):
    P(x, 49)
P(27, 50); P(34, 50)

out = "\n".join("".join(r)[:64].ljust(64, "=") for r in rows)
open("rei_face64.txt", "w").write(out + "\n")
